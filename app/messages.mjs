const patterns = [
  [/^Server membalas HTTP (\d+)\. URL mungkin kedaluwarsa atau memerlukan login\.$/, 'The server replied HTTP $1. The URL may have expired or needs a login.'],
  [/^Alamat baru mengarah ke file yang berbeda \(ukuran (\d+) byte, seharusnya (\d+) byte\)\. Perbarui lagi dengan tautan yang benar\.$/, 'The new address points to a different file ($1 bytes, expected $2 bytes). Refresh again with the correct link.'],
  [/^HTTP (\d+): server tidak memenuhi permintaan unduh\/range\. Klik Lanjut untuk mencoba lagi\.$/, 'HTTP $1: the server did not fulfil the download/range request. Click Resume to try again.'],
  [/^Extractor tidak dapat dijalankan: (.*)$/, 'The extractor could not be started: $1'],
  [/^yt-dlp berhenti dengan kode (.*)$/, 'yt-dlp stopped with code $1'],
  [/^FFmpeg berhenti dengan kode (.*)\.$/, 'FFmpeg stopped with code $1.'],
  [/^Diperbarui (.*) → (.*)$/, 'Updated $1 → $2'],
  [/^Sudah versi terbaru \((.*)\)$/, 'Already up to date ($1)'],
  [/^Gagal memeriksa pembaruan: (.*)$/, 'Update check failed: $1'],
];
export function translateMessage(text, language) {
  if (language !== 'en' || typeof text !== 'string' || !text) return text;
  if (exact[text]) return exact[text];
  for (const [pattern, replacement] of patterns) if (pattern.test(text)) return text.replace(pattern, replacement);
  return text;
}
export const messageCatalog = { exact, patterns };
