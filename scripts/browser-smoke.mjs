import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import http from 'node:http';
import { fileURLToPath } from 'node:url';
import { chromium } from '../.tools/browser-test/node_modules/playwright-core/index.mjs';
import { startServer } from '../app/server.mjs';

const project = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const temporaryRoot = path.join(project, 'tests', '.tmp');
await fs.mkdir(temporaryRoot, { recursive: true });
const temporary = await fs.mkdtemp(path.join(temporaryRoot, 'browser-'));
await fs.mkdir(path.join(project, 'artifacts'), { recursive: true });
const payload = Buffer.alloc(4 * 1024 * 1024, 43);
const source = http.createServer((req, res) => {
  const range = /^bytes=(\d+)-(\d*)$/.exec(req.headers.range || '');
  const start = Number(range?.[1] || 0), end = range?.[2] ? Number(range[2]) : payload.length - 1;
  const headers = { 'Content-Type': 'application/octet-stream', 'Content-Length': end - start + 1, 'Content-Disposition': 'attachment; filename="sample-download.zip"', ETag: '"browser-fixture"' };
  if (range) headers['Content-Range'] = `bytes ${start}-${end}/${payload.length}`;
  res.writeHead(range ? 206 : 200, headers);
  let offset = start;
  const timer = setInterval(() => {
    if (offset > end) { clearInterval(timer); res.end(); return; }
    const next = Math.min(offset + 16384, end + 1); res.write(payload.subarray(offset, next)); offset = next;
  }, req.url === '/slow' ? 60 : 2);
  res.on('close', () => clearInterval(timer));
});
await new Promise(resolve => source.listen(0, '127.0.0.1', resolve));
const sourceOrigin = `http://127.0.0.1:${source.address().port}`;
const app = await startServer({ port: 0, dataDirectory: path.join(temporary, 'state'), downloadDirectory: path.join(temporary, 'downloads') });
let browser;
try {
  browser = await chromium.launch({ channel: 'chrome', headless: true });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1080 }, locale: 'en-US' });
  const errors = []; let expectedValidation = false;
  page.on('pageerror', error => errors.push(error.message));
  page.on('console', msg => { if (msg.type() === 'error' && !(expectedValidation && msg.text().includes('400 (Bad Request)'))) errors.push(msg.text()); });
  await page.goto(app.origin);
  await page.getByText('Connected locally', { exact: false }).waitFor();
  await page.locator('#show-setup').click();
  assert.equal(await page.locator('.setup-steps li').count(), 3);
  await page.locator('#setup-finish').click();
  await page.locator('#tb-add').click();
  await page.locator('#url').fill(sourceOrigin + '/fast');
  await page.getByRole('button', { name: 'Start download' }).click();
  await page.locator('.badge.completed').waitFor({ timeout: 15000 });
  assert.deepEqual(await fs.readFile(app.manager.jobs[0].outputPath), payload);
  await page.locator('#tb-add').click();
  await page.locator('#url').fill(sourceOrigin + '/slow');
  await page.locator('#filename').fill('Arsip-proyek.zip');
  await page.getByRole('button', { name: 'Start download' }).click();
  await page.locator('.badge.downloading').waitFor();
  await page.waitForFunction(() => [...document.querySelectorAll('.job')].some(row => row.querySelector('.badge.downloading') && parseFloat(row.querySelector('.progress>span').style.width) > 0));
  const slowRow = page.locator('.job', { hasText: 'Arsip-proyek.zip' });
  await slowRow.click();
  assert.equal(await page.locator('#tb-resume').isDisabled(), true, 'Resume must be disabled for a running download');
  await page.locator('#tb-pause').click();
  await page.locator('.badge.paused').waitFor();
  await slowRow.click();
  const rowHandle = await slowRow.elementHandle();
  await page.waitForTimeout(1500);
  assert.equal(await rowHandle.evaluate(element => element.isConnected && document.activeElement === element && element.classList.contains('selected')), true, 'Polling must keep the selected row and keyboard focus');
  await page.screenshot({ path: path.join(project, 'artifacts', 'app-desktop.png') });
  await page.locator('#tb-resume').click();
  await page.locator('.badge.downloading').waitFor();
  await slowRow.click({ button: 'right' });
  await page.locator('#context-menu').getByRole('menuitem', { name: 'Cancel download' }).click();
  await page.locator('.badge.cancelled').waitFor();
  const before = app.manager.jobs.length;
  await slowRow.click(); await page.keyboard.press('Delete');
  await page.locator('#confirm-yes').click();
  await slowRow.waitFor({ state: 'detached' });
  assert.equal(app.manager.jobs.length, before - 1, 'Delete must remove the job from the list');
  await page.locator('#tb-add').click();
  await page.locator('#url').fill(sourceOrigin + '/stream.m3u8');
  expectedValidation = true;
  await page.getByRole('button', { name: 'Start download' }).click();
  await page.locator('#form-error').filter({ hasText: 'HLS/DASH' }).waitFor();
  expectedValidation = false;
  await page.locator('#add-cancel').click();
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: path.join(project, 'artifacts', 'app-mobile.png'), fullPage: true });
  const overflow = await page.evaluate(() => document.documentElement.scrollWidth > innerWidth);
  assert.equal(overflow, false, 'Mobile page must not overflow horizontally');
  assert.deepEqual(errors, [], 'Browser errors');
  console.log('PASS: UI submit, completed file checksum, pause, resume, cancel, HLS error, desktop/mobile layout; no browser errors.');
} finally {
  await browser?.close(); await app.close(); source.closeAllConnections(); await new Promise(resolve => source.close(resolve));
  if (path.dirname(path.resolve(temporary)) !== path.resolve(temporaryRoot)) throw new Error('Unsafe browser test cleanup path');
  await fs.rm(temporary, { recursive: true, force: true });
}
